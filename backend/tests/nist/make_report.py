"""Write REPORT.md: the accuracy of the project's code on the NIST StRD, one table per suite.

Run from ``backend/`` with the locked environment:

    AUTH_DISABLED=true .venv-lock/Scripts/python tests/nist/make_report.py
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path[:0] = [str(HERE), str(HERE.parent.parent)]  # strd, and the backend packages

import numpy  # noqa: E402
import pandas  # noqa: E402
import pingouin  # noqa: E402
import scipy  # noqa: E402
import statsmodels  # noqa: E402

import strd  # noqa: E402
import test_nist_strd  # noqa: E402


def _status(m: strd.Measurement) -> str:
    known = m.key in test_nist_strd.XFAIL
    if m.passed:
        return "XPASS (xfail marker is stale)" if known else "pass"
    return "xfail" if known else "FAIL"


def _table(measurements: list[strd.Measurement]) -> list[str]:
    lines = ["| Dataset | NIST difficulty | Quantity | Certified | Ours | LRE ours | LRE baseline | Result |",
             "|---|---|---|---|---|---|---|---|"]
    for m in measurements:
        lines.append(f"| {m.dataset} | {m.difficulty} | {m.quantity} | {m.certified:.15g} | "
                     f"{m.ours:.15g} | {m.lre_ours:.2f} | {m.lre_baseline:.2f} | {_status(m)} |")
    return lines


def build() -> str:
    uni = [m for n in strd.UNIVARIATE for m in strd.measure_univariate(n)]
    anova = [m for n in strd.ANOVA for m in strd.measure_anova(n)]
    out = [
        "# NIST StRD accuracy report",
        "",
        "Generated by `tests/nist/make_report.py`; do not edit by hand. Data and certified values are in "
        "`tests/nist/data/` (see `SOURCE.md`).",
        "",
        "LRE = -log10(|x - c| / |c|), the number of correct significant digits, capped at 15. "
        "A value passes when `LRE(ours) >= LRE(baseline) - 0.5`. The baseline is an independent "
        "computation: numpy for the univariate statistics; `scipy.stats.f_oneway` (F) and two-pass numpy "
        "sums of squares (everything else) for ANOVA. `xfail` is a known, strictly tracked shortfall "
        "(see `test_nist_strd.py`). The F shortfall comes from the between sum of squares: pingouin's "
        "matches the naive two-pass baseline, and both lose digits on data with a large constant "
        "offset (SmLs04 to SmLs09, AtmWtAg), while `f_oneway` centres the data first and keeps about "
        "1.7 digits more. So between SS, between MS and R-squared pass here only because the baseline "
        "is equally weak.",
        "",
        "## Library versions",
        "",
        f"numpy {numpy.__version__}, scipy {scipy.__version__}, pandas {pandas.__version__}, "
        f"statsmodels {statsmodels.__version__}, pingouin {pingouin.__version__} "
        "(the versions of `requirements-dev.lock`).",
        "",
        "## Univariate summary statistics",
        "",
        "Ours: `compute_descriptive_statistics` (the table of the Descriptive tab) and the `summary` of "
        "`calculate_descriptive`. Baseline: `np.mean`, `np.std(ddof=1)`.",
        "",
        *_table(uni),
        "",
        "## One-way ANOVA",
        "",
        "Ours: `core.hypothesis_testing.tables.anova_table` (pingouin); R-squared = SS_between / "
        "(SS_between + SS_within) and residual SD = sqrt(MS_within) are derived from that table.",
        "",
        *_table(anova),
        "",
    ]
    return "\n".join(out)


if __name__ == "__main__":
    (HERE / "REPORT.md").write_text(build(), encoding="utf-8", newline="\n")
    print(f"wrote {HERE / 'REPORT.md'}")
